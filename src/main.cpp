// Two's-complement checksum over a frame, so a valid frame plus its checksum
// byte sums to zero. Must match the sender in DaisyOS.
uint8_t calcchecksum(uint8_t* data_in, size_t data_len) {
  uint8_t raw_sum = 0;

  for (size_t i = 0; i < data_len; i++) {
    raw_sum += data_in[i];
  }

  return (uint8_t)(~raw_sum + 1);
}

// Redefines one glyph from eight bitmap rows, writing each row into its own
// 256-byte plane.
void DefineChar(bool char_ram, uint8_t* payload) {
  uint8_t ch = payload[0];
  uint8_t* ram_ptr;

  ram_ptr = char_ram ? charRAM : gfxRAM;

  for (uint16_t row = 0; row < 8; row++) {
    ram_ptr[ch + (256 * row)] = payload[row + 1];
  }
}

// Restores a single glyph from the ROM font.
void ResetChar(bool char_ram, uint8_t* payload) {
  uint8_t ch = payload[0];
  if (char_ram) {
    CopyGlyphs_P(ch, ch, 1, charROM, charRAM);
  } else {
    CopyGlyphs_P(ch, ch, 1, charROM, gfxRAM);
  }
}

