// Validates a complete frame's checksum and dispatches the drawing command it
// carries. A frame that fails the checksum is dropped silently.
bool HandleDisplayCommand(Buffer* buffer) {
  const uint8_t msg_id = buffer->buffer[1];
  const uint8_t payload_len = buffer->buffer[2];
  const uint8_t checksum = buffer->buffer[buffer->buffer_len - 1];
  uint8_t* payload = &(buffer->buffer[3]);
  uint8_t calc_checksum = calcchecksum(buffer->buffer, buffer->buffer_len - 1);
  if (checksum == calc_checksum) {
    switch (msg_id) {
      case kVideoPutStringAt: {
        uint16_t vidmemcell = 0;
        vidmemcell = buffer->buffer[3] << 8;
        vidmemcell |= buffer->buffer[4];
        uint8_t slen = payload_len - 2;
        memcpy(videodrawptr + vidmemcell, payload + 2, slen);
        memset(attrbmem + vidmemcell, reverse_mode ? 0xFF : 0x00, slen);
        break;
      }
      case kVideoPutAttribsAt: {
        uint16_t atremcell = 0;
        atremcell = (buffer->buffer[3] << 8);
        atremcell |= (buffer->buffer[4]);
        memcpy(attrbmem + atremcell, payload + 2, payload_len - 2);
        break;
      }

      case kVideoToggleAttribAtCursor: {
        attrbmem[(40 * ypos) + xpos] = ~attrbmem[(40 * ypos) + xpos];
        break;
      }

      case kVideoClearAttributeAtCursor: {
        attrbmem[(40 * ypos) + xpos] = 0x0;
        break;
      }

      case kVideoCharOutAt: {
        uint8_t c = payload[0];
        chrout(c);
        break;
      }

      case kVideoLocateCursor: {
        uint8_t x = payload[0];
        uint8_t y = payload[1];
        xpos = x;
        ypos = y;
        break;
      }

      case kVideoClearScreen: {
        clrscr(payload[0]);
        break;
      }

      case kVideoReverseScreen: {
        reverse_mode = (payload[0] == 1);
        memset(attrbmem, reverse_mode ? 0xFF : 0x00, sizeof(attrbmem));
        break;
      }

      case kVideoSetReverseMode: {
        reverse_mode = (payload[0] == 1);
        break;
      }

      case kVideoSetCursorAdvance: {
        bool advance = (payload[0] == 1);
        auto_advance_cursor = advance;
        break;
      }

      case kVideoNewline: {
        newline();
        break;
      }

      case kVideoCursorMove: {
        movecursor((CursorDirection)payload[0]);
        break;
      }

      case kVideoSetScrollLock: {
        auto_scroll = payload[0] == 0 ? true : false;
        break;
      }

      case kVideoScrollScreen: {
        scrollscr();
        break;
      }

      case kVideoSetPixel: {
        VID_SETPIX(payload[0], payload[1], payload[2]);
        break;
      }

      case kVideoDrawLine: {
        int cx0 = payload[0], cy0 = payload[1];
        int cx1 = payload[2], cy1 = payload[3];
        uint8_t on = payload[4];
        int dx = abs(cx1 - cx0), dy = -abs(cy1 - cy0);
        int sx = cx0 < cx1 ? 1 : -1, sy = cy0 < cy1 ? 1 : -1;
        int err = dx + dy;
        for (;;) {
          VID_SETPIX((uint8_t)cx0, (uint8_t)cy0, on);
          if (cx0 == cx1 && cy0 == cy1) {
            break;
          }
          int e2 = 2 * err;
          if (e2 >= dy) {
            err += dy;
            cx0 += sx;
          }
          if (e2 <= dx) {
            err += dx;
            cy0 += sy;
          }
        }
        break;
      }

      case kVideoDrawCircle: {
        int cx = payload[0], cy = payload[1];
        int rx = payload[2], ry = payload[3];
        if (rx == 0 && ry == 0) {
          break;
        }
        uint8_t on = payload[4];
        uint16_t s_deg = ((uint16_t)payload[5] << 8) | payload[6];
        uint16_t e_deg = ((uint16_t)payload[7] << 8) | payload[8];
        bool full = (s_deg == 0 && e_deg == 360);

#define CIRC_PIX(px, py)                                    \
  do {                                                      \
    if ((px) >= 0 && (px) < 80 && (py) >= 0 && (py) < 50) { \
      VID_SETPIX((uint8_t)(px), (uint8_t)(py), on);         \
    }                                                       \
  } while (0)

#define VID_PT(dx, dy)                                                      \
  do {                                                                      \
    if (full) {                                                             \
      CIRC_PIX(cx + (dx), cy + (dy));                                       \
    } else {                                                                \
      float _ang = atan2f(-(float)(dy), (float)(dx)) * (180.0f / M_PI);     \
      if (_ang < 0.0f) _ang += 360.0f;                                      \
      int _a = (int)_ang;                                                   \
      bool _ok = (s_deg <= e_deg) ? (_a >= (int)s_deg && _a <= (int)e_deg)  \
                                  : (_a >= (int)s_deg || _a <= (int)e_deg); \
      if (_ok) {                                                            \
        CIRC_PIX(cx + (dx), cy + (dy));                                     \
      }                                                                     \
    }                                                                       \
  } while (0)

        int32_t a2 = (int32_t)rx * rx, b2 = (int32_t)ry * ry;
        int32_t fa2 = 4 * a2, fb2 = 4 * b2;
        int32_t x, y, sigma;

        x = 0;
        y = ry;
        sigma = 2 * b2 + a2 * (1L - 2L * ry);
        for (; b2 * x <= a2 * y; x++) {
          VID_PT(x, y);
          VID_PT(-x, y);
          VID_PT(x, -y);
          VID_PT(-x, -y);
          if (sigma >= 0) {
            sigma += fa2 * (1L - y);
            y--;
          }
          sigma += b2 * (4L * x + 6L);
        }

        x = rx;
        y = 0;
        sigma = 2 * a2 + b2 * (1L - 2L * rx);
        for (; a2 * y <= b2 * x; y++) {
          VID_PT(x, y);
          VID_PT(-x, y);
          VID_PT(x, -y);
          VID_PT(-x, -y);
          if (sigma >= 0) {
            sigma += fb2 * (1L - x);
            x--;
          }
          sigma += a2 * (4L * y + 6L);
        }

#undef VID_PT
#undef CIRC_PIX
        break;
      }

      case kVideoFloodFill: {
        uint8_t sx = payload[0], sy = payload[1];
        uint8_t fill_val = payload[2];

        if (sx >= 80 || sy >= 50) {
          break;
        }

        uint8_t target = VID_GETPIX(sx, sy);
        if (target > 2 || target == fill_val) {
          break;
        }

        static uint8_t pfx[256], pfy[256];
        int sp = 0;

        VID_SETPIX(sx, sy, fill_val);
        pfx[0] = sx;
        pfy[0] = sy;
        sp = 1;

        static const int8_t ndx[4] = {0, 0, 1, -1};
        static const int8_t ndy[4] = {-1, 1, 0, 0};

        while (sp > 0) {
          sp--;
          uint8_t cx = pfx[sp], cy = pfy[sp];
          for (uint8_t d = 0; d < 4; d++) {
            int nx = (int)cx + ndx[d], ny = (int)cy + ndy[d];
            if (nx < 0 || nx >= 80 || ny < 0 || ny >= 50) {
              continue;
            }
            if (VID_GETPIX(nx, ny) == target) {
              VID_SETPIX((uint8_t)nx, (uint8_t)ny, fill_val);
              if (sp < 256) {
                pfx[sp] = (uint8_t)nx;
                pfy[sp] = (uint8_t)ny;
                sp++;
              }
            }
          }
        }

        break;
      }

      case kVideoDefineChar: {
        DefineChar(CHAR_RAM, payload);
        break;
      }
      case kVideoResetChar: {
        ResetChar(CHAR_RAM, payload);
        break;
      }

      case kVideoDefineGfx: {
        DefineChar(GFX_RAM, payload);
        break;
      }
      case kVideoResetGfx: {
        ResetChar(GFX_RAM, payload);
        break;
      }

      case kVideoDefineCharBulk:
      case kVideoDefineGfxBulk: {
        uint8_t* ram_ptr = (msg_id == kVideoDefineCharBulk) ? charRAM : gfxRAM;
        uint8_t startCh = payload[0];
        uint8_t count = (payload_len - 1) / 8;
        for (uint8_t n = 0; n < count; n++) {
          uint8_t ch = startCh + n;
          for (uint8_t row = 0; row < 8; row++) {
            ram_ptr[ch + 256 * row] = payload[1 + n * 8 + row];
          }
        }
        break;
      }

      case kVideoCopyChar: {
        uint8_t flags = payload[0];
        uint8_t* srcRAM = (flags & 0x01) ? gfxRAM : charRAM;
        uint8_t* dstRAM = (flags & 0x02) ? gfxRAM : charRAM;
        uint8_t start = payload[1];
        uint8_t end = payload[2];
        if (srcRAM == dstRAM) {
          for (uint8_t row = 0; row < 8; row++) {
            dstRAM[end + 256 * row] = srcRAM[start + 256 * row];
          }
        } else {
          uint8_t last = (end >= start) ? end : start;
          uint8_t ch = start;
          for (;;) {
            for (uint8_t row = 0; row < 8; row++) {
              dstRAM[ch + 256 * row] = srcRAM[ch + 256 * row];
            }
            if (ch == last) {
              break;
            }
            ch++;
          }
        }
        break;
      }

      case kVideoPlotChar: {
        uint8_t x = payload[0];
        uint8_t y = payload[1];
        uint8_t ch = payload[2];
        if (x < VID_WIDTH && y < VID_HEIGHT) {
          videodrawptr[(uint16_t)x + (uint16_t)y * VID_WIDTH] = ch;
        }
        break;
      }

      case kVideoFillCells: {
        uint8_t x = payload[0];
        uint8_t y = payload[1];
        uint8_t ch = payload[2];
        uint8_t count = payload[3];
        if (x < VID_WIDTH && y < VID_HEIGHT && count > 0) {
          uint16_t cell = (uint16_t)x + (uint16_t)y * VID_WIDTH;
          uint16_t available = (uint16_t)(VID_WIDTH * VID_HEIGHT) - cell;
          if (count > available) {
            count = (uint8_t)available;
          }
          memset(videodrawptr + cell, ch, count);
          memset(attrbmem + cell, reverse_mode ? 0xFF : 0x00, count);
        }
        break;
      }

      case kVideoMoveBlock: {
        uint8_t fromX = payload[0];
        uint8_t fromY = payload[1];
        uint8_t toX = payload[2];
        uint8_t toY = payload[3];
        uint8_t w = payload[4];
        uint8_t h = payload[5];
        if (fromX < VID_WIDTH && fromY < VID_HEIGHT && toX < VID_WIDTH &&
            toY < VID_HEIGHT && w > 0 && h > 0) {
          uint8_t fillAttr = reverse_mode ? 0xFF : 0x00;
          if (toY < fromY) {
            for (uint8_t row = 0; row < h; row++) {
              uint8_t srcY = fromY + row;
              uint8_t dstY = toY + row;
              if (srcY >= VID_HEIGHT || dstY >= VID_HEIGHT) {
                break;
              }
              uint8_t rowW = w;
              if (fromX + rowW > VID_WIDTH) {
                rowW = VID_WIDTH - fromX;
              }
              if (toX + rowW > VID_WIDTH) {
                uint8_t lim = VID_WIDTH - toX;
                if (lim < rowW) {
                  rowW = lim;
                }
              }
              memmove(videodrawptr + dstY * VID_WIDTH + toX,
                      videodrawptr + srcY * VID_WIDTH + fromX, rowW);
              memmove(attrbmem + dstY * VID_WIDTH + toX,
                      attrbmem + srcY * VID_WIDTH + fromX, rowW);
            }
          } else {
            for (int8_t row = h - 1; row >= 0; row--) {
              uint8_t srcY = fromY + row;
              uint8_t dstY = toY + row;
              if (srcY >= VID_HEIGHT || dstY >= VID_HEIGHT) {
                continue;
              }
              uint8_t rowW = w;
              if (fromX + rowW > VID_WIDTH) {
                rowW = VID_WIDTH - fromX;
              }
              if (toX + rowW > VID_WIDTH) {
                uint8_t lim = VID_WIDTH - toX;
                if (lim < rowW) {
                  rowW = lim;
                }
              }
              memmove(videodrawptr + dstY * VID_WIDTH + toX,
                      videodrawptr + srcY * VID_WIDTH + fromX, rowW);
              memmove(attrbmem + dstY * VID_WIDTH + toX,
                      attrbmem + srcY * VID_WIDTH + fromX, rowW);
            }
          }
          if (payload_len >= 7) {
            uint8_t fillChar = payload[6];
            uint8_t srcRowW = w;
            if (fromX + (uint16_t)srcRowW > VID_WIDTH) {
              srcRowW = VID_WIDTH - fromX;
            }
            uint8_t srcEndX = fromX + srcRowW;
            uint8_t dstEndX = toX + w;
            if (dstEndX > VID_WIDTH) {
              dstEndX = VID_WIDTH;
            }
            uint8_t xOvStart = (fromX > toX) ? fromX : toX;
            uint8_t xOvEnd = (srcEndX < dstEndX) ? srcEndX : dstEndX;
            bool hasXOverlap = xOvStart < xOvEnd;
            for (uint8_t row = 0; row < h; row++) {
              uint8_t srcY = fromY + row;
              if (srcY >= VID_HEIGHT) {
                break;
              }
              bool yOverlap = (srcY >= toY && srcY < (uint16_t)(toY + h));
              if (!yOverlap || !hasXOverlap) {
                memset(videodrawptr + srcY * VID_WIDTH + fromX, fillChar,
                       srcRowW);
                memset(attrbmem + srcY * VID_WIDTH + fromX, fillAttr, srcRowW);
              } else {
                if (xOvStart > fromX) {
                  memset(videodrawptr + srcY * VID_WIDTH + fromX, fillChar,
                         xOvStart - fromX);
                  memset(attrbmem + srcY * VID_WIDTH + fromX, fillAttr,
                         xOvStart - fromX);
                }
                if (xOvEnd < srcEndX) {
                  memset(videodrawptr + srcY * VID_WIDTH + xOvEnd, fillChar,
                         srcEndX - xOvEnd);
                  memset(attrbmem + srcY * VID_WIDTH + xOvEnd, fillAttr,
                         srcEndX - xOvEnd);
                }
              }
            }
          }
        }
        break;
      }

      case kVideoFillBlock: {
        uint8_t x = payload[0];
        uint8_t y = payload[1];
        uint8_t w = payload[2];
        uint8_t h = payload[3];
        uint8_t startChar = payload[4];
        uint8_t endChar = payload[5];
        FillBlock(x, y, w, h, startChar, endChar);
        break;
      }

      case kVideoScrollX: {
        uint8_t sy = payload[0];
        uint8_t sh = payload[1];
        int8_t dir = (int8_t)payload[2];
        if (sy < VID_HEIGHT && sh > 0 && dir != 0) {
          int s = (int)dir % (int)VID_WIDTH;
          if (s < 0) s += VID_WIDTH;
          uint8_t shift = (uint8_t)s;
          while (!in_vblank) {
          }
          uint8_t tmp[VID_WIDTH];
          for (uint8_t row = 0; row < sh; row++) {
            uint8_t cy = sy + row;
            if (cy >= VID_HEIGHT) {
              break;
            }
            uint8_t* line = videodrawptr + cy * VID_WIDTH;
            memcpy(tmp, line, VID_WIDTH);
            memcpy(line + shift, tmp, VID_WIDTH - shift);
            memcpy(line, tmp + VID_WIDTH - shift, shift);
          }
        }
        break;
      }

      case kVideoDrawPoly: {
        uint8_t nE = payload[0];
        uint8_t nD = payload[1];
        uint8_t* pts = &payload[2];

        for (uint8_t pass = 0; pass < 2; pass++) {
          uint8_t n = (pass == 0) ? nE : nD;
          uint8_t off = (pass == 0) ? 0 : nE * 2;
          uint8_t on = (pass == 0) ? 0 : 1;
          if (n == 0) {
            continue;
          }

          for (uint8_t i = 0; i < n; i++) {
            uint8_t i2 = (i + 1 < n) ? i + 1 : 0;
            int cx0 = (int8_t)pts[off + i * 2],
                cy0 = (int8_t)pts[off + i * 2 + 1];
            int cx1 = (int8_t)pts[off + i2 * 2],
                cy1 = (int8_t)pts[off + i2 * 2 + 1];
            int dx = abs(cx1 - cx0), dy = -abs(cy1 - cy0);
            int sx = cx0 < cx1 ? 1 : -1, sy = cy0 < cy1 ? 1 : -1;
            int err = dx + dy;
            for (;;) {
              if (cx0 >= 0 && cx0 < 80 && cy0 >= 0 && cy0 < 50) {
                VID_SETPIX((uint8_t)cx0, (uint8_t)cy0, on);
              }
              if (cx0 == cx1 && cy0 == cy1) {
                break;
              }
              int e2 = 2 * err;
              if (e2 >= dy) {
                err += dy;
                cx0 += sx;
              }
              if (e2 <= dx) {
                err += dx;
                cy0 += sy;
              }
            }
          }
        }
        break;
      }

      default: {
        if (DEBUGOUTPUT) printstr("?VMSG");
        return false;
        break;
      }
    }
  } else {
    if (DEBUGOUTPUT) printstr("?VSUM");
    return false;
  }
  return true;
}

// Drains the UART, reassembling framed commands. Bytes outside a frame are
// discarded until a start-of-packet marker appears, so the link resynchronises
// on its own after a garbled frame. Called from the scanline ISR.
bool PollSerial() {
  static Buffer buffer;
  static uint8_t data = 0;
  while (pserial.available()) {
    data = pserial.read();
    if (buffer.in_frame == false && data == kSOP) {
      BufferInit(&buffer);
      buffer.in_frame = true;
    }
    if (buffer.in_frame == true) {
      BufferAdd(data, &buffer);
      if (buffer.buffer_len ==
          (uint16_t)kMinFrameSize + buffer.buffer[kOffsetPayloadLen]) {
        HandleDisplayCommand(&buffer);
        BufferInit(&buffer);
      }
    } else {
    }
  }
  return true;
}

// Reboots via watchdog timeout, on request from DaisyOS.
void resetArduino() {
  wdt_enable(WDTO_15MS);
  while (1) {
  }
}

bool cpu_ready = false;
// Holds the logo on screen until DaisyOS pulls the ready line low, then clears
// the screen and idles. All real work happens in the scanline ISR.
void loop(void) {
  static bool logoshown = false;

  while (!cpu_ready) {
    cpu_ready = digitalRead(kCpuReadyPin) == LOW;
    if (cpu_ready) {
      memset(videomem, 0, sizeof(videomem));
      xpos = 0;
      ypos = 0;
    } else {
      if (!logoshown) {
        showlogo();
      }
    }
  }

  PollSerial();
  if (vblank) {
    vblank = 0;
    if (digitalRead(52) == HIGH) {
      resetArduino();
    }
  }
}
