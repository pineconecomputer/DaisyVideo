// Fills a rectangle, cycling through the character range as it goes. Clipped
// cells still advance the counter so the pattern stays aligned to the full
// rectangle rather than shifting at the screen edge.
void FillBlock(uint8_t x, uint8_t y, uint8_t w, uint8_t h, uint8_t startChar,
               uint8_t endChar) {
  if (x < VID_WIDTH && y < VID_HEIGHT && w > 0 && h > 0) {
    uint8_t ch = startChar;
    for (uint8_t row = 0; row < h; row++) {
      uint8_t cellY = y + row;
      if (cellY >= VID_HEIGHT) {
        break;
      }
      uint8_t colW = w;
      if (x + colW > VID_WIDTH) {
        colW = VID_WIDTH - x;
      }
      for (uint8_t col = 0; col < colW; col++) {
        uint16_t c = (uint16_t)cellY * VID_WIDTH + x + col;
        videodrawptr[c] = ch;
        if (ch == endChar) {
          ch = startChar;
        } else {
          ch++;
        }
      }
      uint8_t skip = w - colW;
      for (uint8_t s = 0; s < skip; s++) {
        if (ch == endChar) {
          ch = startChar;
        } else {
          ch++;
        }
      }
    }
  }
}

