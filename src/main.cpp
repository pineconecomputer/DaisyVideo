// ===========================================================================
// How the video is generated
// ===========================================================================
//
// There is no video chip here. The ATmega2560 produces a complete composite
// television signal by itself, in software, one scanline at a time.
//
// A composite signal is a single voltage that carries both the picture and
// the timing needed to interpret it. Each scanline begins with a horizontal
// sync pulse, a drop below black that tells the display to start a new line,
// followed by the picture for that line. After the last visible line comes a
// vertical sync, which tells the display to return to the top. Those pulse
// widths are fixed by the NTSC standard and are the _TIME_ values below,
// converted into processor cycles by _CYCLES_PER_US.
//
// Timer1 is configured to run one full period per scanline, so it acts as the
// line clock. Two compare interrupts hang off it: one ends the sync pulse,
// and one fires at the moment picture output must begin. A function pointer,
// line_handler, decides what the second one does, and it is swapped between
// blank_line and active_line as the frame moves in and out of the visible
// region. That pointer swap is cheaper than testing the line number on every
// scanline.
//
// Pixels are shifted out by the USART, not by toggling a pin. The USART is
// put in synchronous master mode, where it clocks bits out of its data
// register at a fixed rate. Writing a byte to it therefore emits eight
// pixels back to back with no processor involvement per pixel, which is the
// only way to reach pixel rates on a 16 MHz part. The pixel clock is set by
// how quickly the code can feed the register, so the instruction count in the
// output loop is part of the timing and cannot be changed freely.
//
// Interrupt latency matters as much as throughput. If the processor is in the
// middle of a long instruction when the timer fires, the handler starts a
// cycle or two late and the line shifts sideways, which the eye sees as a
// ragged edge. The sync handler executes a sleep instruction for this reason:
// waking from sleep takes a fixed number of cycles, so every line starts with
// the same delay instead of a variable one.
//
// The screen is 40 by 25 characters. Glyphs are 8 by 8 pixels and are stored
// as eight 256-byte planes rather than contiguously, so all the row-0 bytes
// sit together, then all the row-1 bytes, and so on. Rendering a scanline
// needs one particular row from every glyph on the line, so this layout turns
// that into a single indexed read per character rather than a multiply.
//
// A second layer gives 80 by 50 pixel graphics by dividing each character
// cell into a 2 by 2 grid and using characters whose bitmaps are the sixteen
// possible quadrant patterns. Dithered variants, where a quadrant is a
// checkerboard rather than solid, extend the same idea to a middle grey. The
// mixed solid and dithered combinations are not in the ROM font, so setup
// generates them at boot.

// Pixel-graphics layer. Each character cell holds a 2 by 2 block of pixels.
#define PIXEL_WIDTH (VID_WIDTH * 2)
#define PIXEL_HEIGHT (VID_HEIGHT * 2)

// Block-graphic character ranges. Codes 0 to 15 use the four low bits as a
// mask of which quadrants are solid. The dithered set mirrors that layout at
// a different base. The mixed set covers combinations of solid and dithered
// quadrants and is looked up through a table rather than computed.
const uint8_t kSolidBlockFirst = 0;
const uint8_t kSolidBlockLast = 15;
const uint8_t kDitherBlockFirst = 160;
const uint8_t kDitherBlockLast = 175;
const uint8_t kMixedBlockFirst = 176;
const uint8_t kMixedBlockLast = 225;
const uint8_t kMixedBlockCount = kMixedBlockLast - kMixedBlockFirst + 1;

// Glyph storage. One character set is eight planes of 256 bytes, one plane
// per pixel row.
const uint16_t kCharsPerSet = 256;
const uint16_t kGlyphRows = 8;
const uint16_t kFontPageBytes = (uint16_t)kCharsPerSet * kGlyphRows;

