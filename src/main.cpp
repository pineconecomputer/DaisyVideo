// Decodes a block-graphic character back into its two 4-bit masks: which of
// the cell's four quadrants are solid and which are dithered. Non-graphic
// characters decode to empty so callers can treat any cell uniformly.
static inline void extractPixelBits(uint8_t ch, uint8_t& solid,
                                    uint8_t& dither) {
  if (ch <= kSolidBlockLast) {
    solid = ch;
    dither = 0;
  } else if (ch >= kDitherBlockFirst && ch <= kDitherBlockLast) {
    solid = 0;
    dither = ch - kDitherBlockFirst;
  } else if (ch >= kMixedBlockFirst && ch <= kMixedBlockLast) {
    uint8_t sd = pgm_read_byte(&mixedRev[ch - kMixedBlockFirst]);
    solid = sd >> 4;
    dither = sd & 0x0F;
  } else {
    solid = 0;
    dither = 0;
  }
}

// Inverse of extractPixelBits: picks the character code that renders a given
// combination of solid and dithered quadrants. Pure-solid and pure-dither
// cases are arithmetic; mixed cells need the lookup table.
static inline uint8_t packPixelBits(uint8_t solid, uint8_t dither) {
  if (dither == 0) {
    return solid;
  }
  if (solid == 0) {
    return kDitherBlockFirst + dither;
  }
  return pgm_read_byte(&mixedFwd[(solid << 4) | dither]);
}

#define VID_SETPIX(px, py, on)                                                 \
  do {                                                                         \
    uint8_t _cx = (uint8_t)(px) >> 1, _cy = (uint8_t)(py) >> 1;                \
    if (_cx < VID_WIDTH && _cy < VID_HEIGHT) {                                 \
      uint8_t* _cell = &videodrawptr[_cx + _cy * VID_WIDTH];                   \
      uint8_t _s, _d;                                                          \
      extractPixelBits(*_cell, _s, _d);                                        \
      uint8_t _mask = 1 << (((uint8_t)(px) & 1) | (((uint8_t)(py) & 1) << 1)); \
      _s &= ~_mask;                                                            \
      _d &= ~_mask;                                                            \
      if ((on) == 1)                                                           \
        _s |= _mask;                                                           \
      else if ((on) == 2)                                                      \
        _d |= _mask;                                                           \
      *_cell = packPixelBits(_s, _d);                                          \
    }                                                                          \
  } while (0)

#define VID_GETPIX(px, py)                                                  \
  ({                                                                        \
    uint8_t _c =                                                            \
        videodrawptr[((px) >> 1) + (uint16_t)((py) >> 1) * VID_WIDTH];      \
    uint8_t _s2, _d2;                                                       \
    extractPixelBits(_c, _s2, _d2);                                         \
    uint8_t _mask2 = 1 << (((px) & 1) | (((py) & 1) << 1));                 \
    (_s2 & _mask2) ? (uint8_t)1 : (_d2 & _mask2) ? (uint8_t)2 : (uint8_t)0; \
  })

// Reverses the bits in a byte, swapping progressively smaller groups.
uint8_t bitReverse(uint8_t b) {
  b = (b & 0xF0) >> 4 | (b & 0x0F) << 4;
  b = (b & 0xCC) >> 2 | (b & 0x33) << 2;
  b = (b & 0xAA) >> 1 | (b & 0x55) << 1;
  return b;
}
// Copies a run of glyphs from a PROGMEM font into character RAM. Glyph rows
// are stored in eight 256-byte planes rather than contiguously, so each row
// needs its own copy at a 256-byte stride.
void CopyGlyphs_P(uint16_t from_num, uint16_t to_num, uint16_t num_chars,
                  const uint8_t* from_rom, uint8_t* to_ram) {
  memcpy_P(to_ram + to_num + (0 * 256), from_rom + from_num + (0 * 256),
           num_chars);
  memcpy_P(to_ram + to_num + (1 * 256), from_rom + from_num + (1 * 256),
           num_chars);
  memcpy_P(to_ram + to_num + (2 * 256), from_rom + from_num + (2 * 256),
           num_chars);
  memcpy_P(to_ram + to_num + (3 * 256), from_rom + from_num + (3 * 256),
           num_chars);
  memcpy_P(to_ram + to_num + (4 * 256), from_rom + from_num + (4 * 256),
           num_chars);
  memcpy_P(to_ram + to_num + (5 * 256), from_rom + from_num + (5 * 256),
           num_chars);
  memcpy_P(to_ram + to_num + (6 * 256), from_rom + from_num + (6 * 256),
           num_chars);
  memcpy_P(to_ram + to_num + (7 * 256), from_rom + from_num + (7 * 256),
           num_chars);
}

// CopyGlyphs_P against a chosen 2048-byte font page in ROM.
void CopyGlyphsFromPage_P(uint16_t from_num, uint8_t page, uint16_t to_num,
                          uint16_t num_chars, const uint8_t* from_rom,
                          uint8_t* to_ram) {
  CopyGlyphs_P(from_num + kFontPageBytes * page, to_num, num_chars, from_rom,
               to_ram);
}

// Copies a rectangular block of glyphs, used for multi-cell images whose tiles
// sit on a 20-column pitch in the source ROM.
void CopyGob_P(uint8_t base_char_num, uint8_t width, uint8_t height,
               uint8_t to_num, uint8_t* from_rom, uint8_t* to_ram) {
  for (uint8_t charrow = 0; charrow < height; charrow++) {
    CopyGlyphs_P(base_char_num + (kLogoTilePitch * charrow),
                 to_num + (kLogoTilePitch * charrow), width,
                 from_rom, to_ram);
  }
}

// Loads the boot logo tiles into character RAM.
void CopyGraphics_P(uint8_t* from_rom, uint8_t* to_ram) {
  CopyGob_P(kLogoFirstChar, kLogoWidthChars, kLogoHeightChars, kLogoFirstChar,
            from_rom, to_ram);
}

// Restores the whole character set from ROM, discarding user redefinitions.
void RestoreCharROM(void) {
  CopyGlyphs_P(0, 0, kCharsPerSet, charROM, charRAM);
}

// Inverts every glyph bitmap in place, optionally leaving row 0 of each plane
// alone so the blank character stays blank.
void InvertGlyphs(uint8_t* ram, uint16_t size, bool zero) {
  for (uint16_t index = 0; index < size; index++) {
    if (zero && index % kCharsPerSet == 0) {
      continue;
    }
    *(ram + index) = *(ram + index) ^ 0xff;
  }
}

// Boot. Configures the USART as a synchronous shift register clocked out as
// pixels, sets up Timer1 to free-run at one NTSC scanline per period, clears
// the framebuffers, and pre-renders the 50 mixed solid/dither glyphs that the
// pixel layer needs but the ROM font does not contain.
void setup(void) {
  pinMode(kCpuReadyPin, INPUT_PULLUP);
  pollSerial = pserial.begin(115200);
  cli();
  UBRR0 = 0;
  XCK0_DDR |= _BV(XCK0);
  UCSR0C = _BV(UMSEL00) | _BV(UMSEL01);
  DDR_VID |= _BV(VID_PIN);
  DDR_SYNC |= _BV(SYNC_PIN);
  PORT_VID &= ~_BV(VID_PIN);
  PORT_SYNC |= _BV(SYNC_PIN);
  TCCR1A = _BV(COM1A1) | _BV(COM1A0) | _BV(WGM11);
  TCCR1B = _BV(WGM13) | _BV(WGM12) | _BV(CS10);
  ICR1 = _NTSC_CYCLES_SCANLINE;
  OCR1A = _CYCLES_HSYNC;
  OCR1B = _NTSC_CYCLES_OUTPUT_START - kOutputStartLead;
  TIMSK1 = _BV(OCIE1B);
  TIMSK0 = 0;
  SMCR = _BV(SE);
  memset(videomem, 0x00, sizeof(videomem));
  memset(attrbmem, 0x00, sizeof(attrbmem));
  memset(charRAM, 0x00, sizeof(charRAM));
  memset(gfxRAM, 0x00, sizeof(gfxRAM));
  memcpy_P(gfxRAM, daisyROM, sizeof(gfxRAM));
  sei();
  RestoreCharROM();
#if 0
  InitCustomChars();
#endif

  for (uint8_t i = 0; i < kMixedBlockCount; i++) {
    uint8_t sd = pgm_read_byte(&mixedRev[i]);
    uint8_t solidBits = sd >> 4, ditherBits = sd & 0x0F;
    uint8_t ch = kMixedBlockFirst + i;
    for (uint8_t row = 0; row < 8; row++) {
      uint8_t leftBit = (row < 4) ? 0 : 2;
      uint8_t rightBit = (row < 4) ? 1 : 3;
      uint8_t ls = (solidBits >> leftBit) & 1
                       ? 1
                       : ((ditherBits >> leftBit) & 1 ? 2 : 0);
      uint8_t rs = (solidBits >> rightBit) & 1
                       ? 1
                       : ((ditherBits >> rightBit) & 1 ? 2 : 0);
      uint8_t lb = (ls == 1) ? 0xF0 : (ls == 2) ? ((row & 1) ? 0x50 : 0xA0) : 0;
      uint8_t rb = (rs == 1) ? 0x0F : (rs == 2) ? ((row & 1) ? 0x05 : 0x0A) : 0;
      charRAM[ch + row * kCharsPerSet] = lb | rb;
    }
  }
}
// End of horizontal sync. Re-enables interrupts and sleeps so the CPU wakes on
// the next compare with predictable latency -- sleeping is what keeps the
// wake-up jitter low enough for a stable picture.
ISR(TIMER1_COMPA_vect) {
  sei();
  asm("sleep\n");
}

// Fires once per scanline at the point where pixel output must begin. Calls
// whichever line handler is active, then services the serial port in the time
// left over.
ISR(TIMER1_COMPB_vect) {
  line_handler();
  scanline++;
  pollSerial();
}
// Scanline handler for the non-visible part of the frame. Manages vertical
// sync width and, at the top of the display window, resets the framebuffer
// pointers and switches over to active_line.
void blank_line(void) {
  pollSerial();
  if (scanline == _NTSC_LINE_STOP_VSYNC) {
    OCR1A = _CYCLES_HSYNC;
  } else if (scanline == _NTSC_LINE_MID - (VID_HEIGHT * CELL_HEIGHT) / 2) {
    TIMSK1 = _BV(OCIE1A) | _BV(OCIE1B);
    videoptr = videomem;
    attrbptr = attrbmem;
    line_handler = &active_line;
    in_vblank = false;
    inGfxMode = ((*attrbptr & 0x0F) == 0x01);
    gfxattrib = ((*attrbptr & 0xF0) == 0xF0) ? 0xff : 0x00;
  } else if (scanline > _NTSC_LINE_FRAME) {
    OCR1A = _CYCLES_VSYNC;
    scanline = 0;
  }
}

// Scanline handler that shifts one row of pixels out of the USART. Reads each
// cell's glyph row from character or graphics RAM and XORs the attribute byte
// to apply reverse video. The leading zero writes produce the back porch, and
// the instruction count in these loops sets the pixel clock -- do not add work
// here. Advances to the next text row every CELL_HEIGHT scanlines.
void active_line(void) {
  register uint8_t* charPtr = videoptr;
  register uint8_t* attribute = attrbptr;

  register uint8_t gfxattrb = gfxattrib;
  uint8_t p;
  static byte charRow = 0;
  register int charCol_offset = (charRow << 8);
  p = VID_WIDTH;

  UCSR0B = _BV(TXEN0);
  while ((UCSR0A & _BV(UDRE0)) == 0) {
  }
  UDR0 = 0;
  while ((UCSR0A & _BV(UDRE0)) == 0) {
  }
  UDR0 = 0;
  while ((UCSR0A & _BV(UDRE0)) == 0) {
  }
  UDR0 = 0;

  if (inGfxMode) {
    while ((UCSR0A & _BV(UDRE0)) == 0) {
  }
    UDR0 = 0;
    while (p--) {
      UDR0 = gfxRAM[charCol_offset + *charPtr++] ^ gfxattrb;
      asm("nop");
      asm("nop");
    }
  } else {
    while ((UCSR0A & _BV(UDRE0)) == 0) {
  }
    UDR0 = 0;
    while (p--) {
      UDR0 = charRAM[charCol_offset + *charPtr++] ^ *(attribute++);
    }
  }
  while ((UCSR0A & _BV(TXC0)) == 0) {
  }
  UCSR0B = 0;
  if (++charRow == CELL_HEIGHT) {
    charRow = 0;
    if (scanline == _NTSC_LINE_MID + (VID_HEIGHT * CELL_HEIGHT) / 2) {
      TIMSK1 = _BV(OCIE1B);
      line_handler = &blank_line;
      vblank = 1;
      in_vblank = true;
    } else {
      videoptr += VID_WIDTH;
      attrbptr += VID_WIDTH;
      inGfxMode = ((*attrbptr & 0x0F) == 0x01);
      gfxattrib = (*attrbptr & 0xF0) == 0xF0 ? 0xff : 0x00;
    }
  }
}
// Writes one character at the cursor and advances it, wrapping and scrolling
// at the screen edges. Carriage return is handled as a newline.
void chrout(uint8_t ascii) {
  if (ascii == 13) {
    newline();
    return;
  }
  if (ascii <= 255) {
    uint16_t cell = (uint16_t)xpos + (uint16_t)ypos * VID_WIDTH;
    videodrawptr[cell] = ascii;
    attrbmem[cell] = reverse_mode ? 0xFF : 0x00;
    if (auto_advance_cursor) {
      xpos++;
      if (xpos >= VID_WIDTH) {
        xpos = 0;
        ypos++;
        if (ypos >= VID_HEIGHT) {
          if (auto_scroll) {
            scrollscr();
          }
          xpos = 0;
          ypos = VID_HEIGHT - 1;
        }
      }
    }
  }
}

// chrout, but forces the target cell to reverse video first.
void chrout_reverse(uint8_t ascii) {
  attrbmem[xpos + ypos * VID_WIDTH] = 0xff;
  chrout(ascii);
}

// Fills the screen with one character and resets every attribute to the
// current video polarity.
void clrscr(byte val) {
  memset(videodrawptr, val, sizeof(videomem));
  memset(attrbmem, reverse_mode ? 0xFF : 0x00, sizeof(attrbmem));
}
// Scrolls the display up one text row and blanks the bottom row, moving
// characters and attributes together so highlighting travels with its text.
void scrollscr(void) {
  for (uint8_t line = 1; line < VID_HEIGHT; line++) {
    memcpy(&videodrawptr[(line - 1) * VID_WIDTH],
           &videodrawptr[VID_WIDTH * line], VID_WIDTH);
    memcpy(&attrbmem[(line - 1) * VID_WIDTH], &attrbmem[VID_WIDTH * line],
           VID_WIDTH);
  }
  memset(&videodrawptr[(VID_HEIGHT - 1) * VID_WIDTH], 0x00, VID_WIDTH);
  memset(&attrbmem[(VID_HEIGHT - 1) * VID_WIDTH], reverse_mode ? 0xFF : 0x00,
         VID_WIDTH);
}
// Writes a NUL-terminated string at the cursor.
void printstr(char* string) {
  while (*string) {
    chrout(*string++);
  }
}
// Writes a string horizontally centred on the given row.
void centerstr(char* string, uint8_t y) {
  uint8_t x = (VID_WIDTH / 2) - (uint8_t)strlen(string) / 2;
  gotoxy(x, y);
  printstr(string);
}
// Moves the cursor, ignoring either coordinate that falls outside the screen
// so a bad value cannot park the cursor off-screen.
void gotoxy(int x, int y) {
  if (x != xpos) {
    if (x >= 0 && x < VID_WIDTH) {
      xpos = x;
    }
  }
  if (y != ypos) {
    if (y >= 0 && y < VID_HEIGHT) {
      ypos = y;
    }
  }
}

// Moves to the start of the next row, scrolling if that runs past the bottom.
void newline(void) {
  xpos = 0;
  ypos++;
  if (ypos >= VID_HEIGHT) {
    if (auto_scroll) {
      scrollscr();
    }
    xpos = 0;
    ypos = VID_HEIGHT - 1;
  }
}

typedef enum {
  kCursorUp = 1,
  kCursorRight = 2,
  kCursorDown = 3,
  kCursorLeft = 4,
} CursorDirection;

// Moves the cursor one cell, clamping at the screen edges rather than wrapping.
void movecursor(CursorDirection direction) {
  switch (direction) {
    case kCursorUp: {
      ypos--;
      if (ypos < 0) {
        ypos = 0;
      }
      break;
    }
    case kCursorRight: {
      xpos++;
      if (xpos == VID_WIDTH) {
        if (ypos == VID_HEIGHT - 1) {
          if (auto_scroll) {
            scrollscr();
          }
          xpos = 0;
        } else {
          xpos = 0;
          ypos++;
        }
      }
      break;
    }
    case kCursorDown: {
      ypos++;
      if (ypos == VID_HEIGHT) {
        if (auto_scroll) {
          scrollscr();
        }
        ypos = VID_HEIGHT - 1;
      }
      break;
    }
    case kCursorLeft: {
      xpos--;
      if (xpos < 0) {
        if (ypos != 0) {
          xpos = VID_WIDTH - 1;
          ypos--;
        } else {
          xpos = 0;
        }
      }
      break;
    }
    default:
      break;
  }
}

// Turns on one pixel in the 80x50 block-graphics layer. Each character cell
// holds a 2x2 quadrant, so the pixel maps to one bit of one cell.
void setpix(signed char x, signed char y) {
  byte xChar, yChar, blockChar;

  if (x > 79 || x < 0 || y > 49 || y < 0) {
    return;
  }
  xChar = x >> 1;
  yChar = y >> 1;
  blockChar = 1 << ((x & 1) | ((y & 1) << 1));
  videodrawptr[xChar + yChar * VID_WIDTH] |= blockChar;
}
// Clears one pixel, leaving the other three quadrants of the cell alone.
void clrpix(signed char x, signed char y) {
  byte xChar, yChar, blockChar;

  if (x > 79 || x < 0 || y > 49 || y < 0) {
    return;
  }
  xChar = x >> 1;
  yChar = y >> 1;
  blockChar = 1 << ((x & 1) | ((y & 1) << 1));
  videodrawptr[xChar + yChar * VID_WIDTH] &= ~blockChar;
}
// Flips one pixel. Useful for drawing that can be undone by redrawing.
void xorpix(signed char x, signed char y) {
  byte xChar, yChar, blockChar;

  if (x > 79 || x < 0 || y > 49 || y < 0) {
    return;
  }
  xChar = x >> 1;
  yChar = y >> 1;
  blockChar = 1 << ((x & 1) | ((y & 1) << 1));
  videodrawptr[xChar + yChar * VID_WIDTH] ^= blockChar;
}
// Bresenham line between two pixels. The per-pixel operation is passed in, so
// the same walk serves set, clear, and xor drawing.
void line(signed char x1, signed char y1, signed char x2, signed char y2,
          void (*oppix)(signed char x, signed char y)) {
  signed char dx, dy, sx, sy, dx2, dy2, dd2, err;

  if (x2 >= x1) {
    dx = x2 - x1;
    sx = 1;
  } else {
    dx = x1 - x2;
    sx = -1;
  }
  if (y2 >= y1) {
    dy = y2 - y1;
    sy = 1;
  } else {
    dy = y1 - y2;
    sy = -1;
  }
  dx2 = dx << 1;
  dy2 = dy << 1;
  if (dx >= dy) {
    err = dx - dy2;
    dd2 = dx2 - dy2;
    while (x1 != x2) {
      oppix(x1, y1);
      x1 += sx;
      if (err < 0) {
        err += dd2;
        y1 += sy;
      } else {
        err -= dy2;
      }
    }
  } else {
    err = dy - dx2;
    dd2 = dy2 - dx2;
    while (y1 != y2) {
      oppix(x1, y1);
      y1 += sy;
      if (err < 0) {
        err += dd2;
        x1 += sx;
      } else {
        err -= dx2;
      }
    }
  }
  oppix(x2, y2);
}

